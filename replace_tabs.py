def replace_block(text, preset_id, new_content):
    pattern = re.compile(r"\{\s*id:\s*'" + preset_id + r"'.*?`,\n\s*\}", re.DOTALL)
    # use a lambda to avoid backreference parsing in repl string
    return pattern.sub(lambda m: "{\n" + new_content + "\n  }", text, 1)

